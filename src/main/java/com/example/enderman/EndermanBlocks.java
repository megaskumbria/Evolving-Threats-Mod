package com.example.enderman;

import net.minecraft.util.Mth;

/**
 * Как часто эндермен берёт блок рядом и ставит его на землю.
 * Сам поиск блока остаётся у игры: один случайный блок в паре шагов,
 * и только из тех, которые эндермену можно нести.
 * Если в мире выключено «мобы ломают блоки», он ничего не трогает.
 *
 * <p>FIXED: с первого дня, от шкалы угрозы не растёт.
 */
public final class EndermanBlocks {

	// ===================== SETTINGS (меняй эти числа) =====================

	/** false — берёт и ставит блоки как в обычной игре. */
	public static final boolean ENABLED = true;

	/**
	 * Пауза между попытками ВЗЯТЬ блок, в тиках. 20 тиков = 1 секунда.
	 * 5 = в среднем раз в четверть секунды. В обычной игре около 10 (раз в полсекунды).
	 * Меньше — хватает чаще. 1 = пробует каждый тик.
	 * Это не гарантия: смотрит один случайный блок рядом. Воздух и камень он не берёт.
	 */
	public static final int TAKE_INTERVAL = 5;

	/**
	 * Пауза между попытками ПОСТАВИТЬ блок, который уже несёт, в тиках.
	 * 40 = в среднем раз в 2 секунды. В обычной игре около 1000 (раз в 50 секунд),
	 * поэтому блок долго висит в руках и почти не переставляется.
	 * Меньше — быстрее кладёт. 1 = ставит почти сразу, как нашёл место.
	 * Место тоже случайное: нужен воздух над твёрдым блоком, иначе попытка пустая.
	 */
	public static final int PLACE_INTERVAL = 40;

	// ========================================================================

	private EndermanBlocks() {
	}

	/** Число для броска «взять». Если механика выключена — как посчитала игра. */
	public static int takeInterval(int vanillaTicks) {
		return interval(vanillaTicks, TAKE_INTERVAL);
	}

	/** Число для броска «поставить». Если механика выключена — как посчитала игра. */
	public static int placeInterval(int vanillaTicks) {
		return interval(vanillaTicks, PLACE_INTERVAL);
	}

	private static int interval(int vanillaTicks, int ours) {
		if (!ENABLED) {
			// Так же делит паузу игра, когда эта механика выключена.
			return Mth.positiveCeilDiv(vanillaTicks, 2);
		}
		return Math.max(1, ours);
	}
}
